    [BookCodePostgresFact]
    public async Task NativeEnumMigrationPreservesNotesAndIsIdempotent()
    {
        await using var fixture = await Fixture.CreateAsync();
        await using var db = fixture.Context();
        var copy = await db.BookCopies.SingleAsync(); copy.IsAvailable = true; copy.Location = fixture.ShelfA;
        var incident = await db.BookIncidents.SingleAsync(); incident.Severity = BookIncidentSeverity.Light; incident.Status = BookIncidentStatus.CompensationPending;
        await db.SaveChangesAsync();
        await db.Database.OpenConnectionAsync();
        var connection = (NpgsqlConnection)db.Database.GetDbConnection();
        await new NpgsqlCommand("CREATE TYPE book_condition AS ENUM ('new','good','fair','damaged','lost'); ALTER TABLE book_copies ALTER COLUMN condition TYPE book_condition USING condition::book_condition", connection).ExecuteNonQueryAsync();
        foreach (var operation in new AddLightDamageCondition().UpOperations.Cast<SqlOperation>())
            await new NpgsqlCommand(operation.Sql, connection).ExecuteNonQueryAsync();
        foreach (var operation in new BackfillVerifiedLightDamage().UpOperations.Cast<SqlOperation>())
        {
            await new NpgsqlCommand(operation.Sql, connection).ExecuteNonQueryAsync();
            await new NpgsqlCommand(operation.Sql, connection).ExecuteNonQueryAsync();
        }
        await connection.ReloadTypesAsync();
        db.ChangeTracker.Clear();
        Assert.Equal(BookCondition.LightDamaged, (await db.BookCopies.SingleAsync()).Condition);
        Assert.Equal(1, (await db.Books.SingleAsync()).AvailableCopies);
        Assert.Equal("Ghi nhận ban đầu.", (await db.BookIncidents.SingleAsync()).Description);
    }

