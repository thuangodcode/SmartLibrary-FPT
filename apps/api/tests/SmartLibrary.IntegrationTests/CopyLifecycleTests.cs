            fixture.CopyId = copy.Id; fixture.LoanId = loan.Id; fixture.IncidentId = incident.Id; fixture.StaffId = staff.Id;
            return fixture;
        }
        public async ValueTask DisposeAsync()
        {
            await using var connection = new NpgsqlConnection(root); await connection.OpenAsync();
            await new NpgsqlCommand($"DROP SCHEMA {schema} CASCADE", connection).ExecuteNonQueryAsync();
        }
