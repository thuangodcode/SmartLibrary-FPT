    [BookCodePostgresFact]
    public async Task SevereDamageRemainsBlockedAfterPaymentUntilExplicitPhysicalRecovery()
    {
        await using var fixture = await Fixture.CreateAsync();
        await using (var db = fixture.Context())
        {
            var service = Service(db);
            var confirm = await service.ConfirmIncidentAsync(fixture.IncidentId, new() { Severity = "Severe", Notes = "Rơi nhiều trang." }, fixture.StaffId);
            Assert.True(confirm.IsSuccess, confirm.Error);
            var fine = await db.Fines.SingleAsync();
            Assert.True((await service.PayFineAsync(fine.Id, fixture.StaffId)).IsSuccess);
            Assert.Equal(BookCondition.Damaged, (await db.BookCopies.SingleAsync()).Condition);
            Assert.False((await db.BookCopies.SingleAsync()).IsAvailable);
        }
        await using (var db = fixture.Context())
            Assert.IsType<ConflictObjectResult>(await new BookCopiesController(db).TransferLocations(new([new(fixture.CopyId, fixture.ShelfA)]), Service(db)));
        await using (var db = fixture.Context())
        {
            var service = Service(db);
            var recover = await service.RestoreIncidentCopyAsync(fixture.IncidentId, new() { Condition = "Fair", Notes = "Đã đóng lại gáy và bổ sung đủ trang." }, fixture.StaffId);
            Assert.True(recover.IsSuccess, recover.Error);
            Assert.Equal(BookCondition.Fair, (await db.BookCopies.SingleAsync()).Condition);
            Assert.Equal(FineStatus.Paid, (await db.Fines.SingleAsync()).Status);
            Assert.Contains("Đã đóng lại gáy", recover.Data!.Description);
            Assert.False((await service.RestoreIncidentCopyAsync(fixture.IncidentId, new() { Notes = "Thử lần nữa" }, fixture.StaffId)).IsSuccess);
        }
    }

