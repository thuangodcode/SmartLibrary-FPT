            await using var db = fixture.Context();
            await db.Database.OpenConnectionAsync();
            await new NpgsqlCommand(db.Database.GenerateCreateScript(), (NpgsqlConnection)db.Database.GetDbConnection()).ExecuteNonQueryAsync();
