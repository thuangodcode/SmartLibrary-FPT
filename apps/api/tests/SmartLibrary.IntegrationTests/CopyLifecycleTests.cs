    [BookCodePostgresFact]
    public async Task FreshLocalSchemaSupportsLoginProfilesWithRoleScopedPermissions()
    {
        await using var fixture = await Fixture.CreateAsync();
        await using var db = fixture.Context();
        var staff = await db.UserProfiles.SingleAsync(item => item.Id == fixture.StaffId);
        var reader = await db.UserProfiles.SingleAsync(item => item.Id != fixture.StaffId);
        var process = new Permission { Code = "borrow:process" };
        var create = new Permission { Code = "borrow:create" };
        db.AddRange(new RolePermission { RoleId = staff.RoleId, Permission = process },
            new RolePermission { RoleId = reader.RoleId, Permission = create });
        await db.SaveChangesAsync();

        var config = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string?>
        {
            ["ConnectionStrings:DefaultConnection"] = db.Database.GetConnectionString()
        }).Build();
        using var http = new HttpClient();
        using var cache = new MemoryCache(new MemoryCacheOptions());
        var auth = new SupabaseAuthService(http, null!, config, NullLogger<SupabaseAuthService>.Instance, cache);
        // Exercise the real raw-SQL profile query against the schema generated by EF,
        // the same combination that failed after creating the isolated demo database.
        foreach (var (user, role, permission) in new[] { (staff, "Librarian", "borrow:process"), (reader, "Reader", "borrow:create") })
        {
            var profile = await auth.GetUserProfileWithPermissionsAsync(user.Id.ToString());
            Assert.NotNull(profile);
            var json = JsonSerializer.SerializeToElement(profile);
            Assert.Equal(role, json.GetProperty("role").GetString());
            Assert.Equal(permission, Assert.Single(json.GetProperty("permissions").EnumerateArray()).GetString());
        }
        staff.IsActive = false;
        await db.SaveChangesAsync();
        Assert.Null(await auth.GetUserProfileWithPermissionsAsync(staff.Id.ToString()));
    }

